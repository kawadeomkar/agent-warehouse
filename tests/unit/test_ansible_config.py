"""What ansible.cfg makes of the connections and inventories every recipe runs with.

Pipelining is on for the modules run on this machine as for those on the VMs. Set only for ssh, it left each module
the controller runs - every community.proxmox call and uri request, which carry the Proxmox token, and the Tailscale
API's, which carry its credential - written into ~/.ansible/tmp as a file before it ran, and kept there for good under
ANSIBLE_KEEP_REMOTE_FILES=1 or by a run killed part way.

Only the inventory plugins the project's inventories need are enabled: never script, which runs any executable file in
the inventory folder, nor auto, which loads any inventory plugin a YAML file there names. Each inventory the project
hands Ansible still parses with them: inventory/'s files, init's own and the one Vagrant's provisioner writes.
"""

from __future__ import annotations

import configparser
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

from harness import _env

REPO = Path(__file__).resolve().parents[2]
INVENTORY = Path(sys.executable).with_name("ansible-inventory")
# What Vagrant's Ansible provisioner writes for the Vagrantfile's VM: INI, with the groups it names.
VAGRANT_INVENTORY = """# Generated by Vagrant

default ansible_host=127.0.0.1 ansible_port=2222 ansible_user='vagrant' ansible_ssh_private_key_file='/k'

[claude_vms]
default
"""


def _config() -> configparser.ConfigParser:
    config = configparser.ConfigParser(interpolation=None)
    config.read(REPO / "ansible.cfg")
    return config


def test_modules_run_on_this_machine_are_pipelined_as_those_on_the_vms(tmp_path: Path) -> None:
    probe = (
        "from ansible.plugins.loader import connection_loader, init_plugin_loader\n"
        "from ansible.playbook.play_context import PlayContext\n"
        "init_plugin_loader([])\n"
        "for name in ('local', 'ssh'):\n"
        "    connection = connection_loader.get(name, PlayContext(), None)\n"
        "    connection.set_options(var_options={})\n"
        "    print(name, connection.get_option('pipelining'))\n"
    )
    # Run from the checkout, as every recipe is, so Ansible reads the checkout's own config; nothing of this
    # machine's Ansible settings, and a HOME of its own for the folders Ansible makes.
    env = {name: value for name, value in os.environ.items() if not name.startswith("ANSIBLE_")}
    env["HOME"] = str(tmp_path)
    result = subprocess.run(
        [sys.executable, "-c", probe], cwd=REPO, env=env, capture_output=True, text=True, check=False
    )
    assert result.returncode == 0, result.stderr
    assert result.stdout.split("\n")[:2] == ["local True", "ssh True"], result.stdout


def test_no_inventory_plugin_runs_or_loads_code() -> None:
    enabled = {name.strip() for name in _config().get("inventory", "enable_plugins").split(",")}
    assert enabled == {"yaml", "ini"}


def _hosts(tmp_path: Path, source: Path) -> dict:
    enabled = _config().get("inventory", "enable_plugins")
    result = subprocess.run(
        [str(INVENTORY), "-i", str(source), "--list"],
        env=_env(tmp_path, f"[inventory]\nenable_plugins = {enabled}\n", HOME=str(tmp_path / "home")),
        stdin=subprocess.DEVNULL,
        capture_output=True,
        text=True,
        check=False,
    )
    assert result.returncode == 0, result.stdout + result.stderr
    return json.loads(result.stdout)


def test_every_inventory_the_project_hands_ansible_parses_and_none_runs(tmp_path: Path) -> None:
    folder = tmp_path / "inventory"
    folder.mkdir()
    shutil.copy(REPO / "inventory" / "controller.yml", folder)
    shutil.copy(REPO / "inventory" / "hosts.yml.example", folder / "hosts.yml")
    ran = tmp_path / "ran"
    script = folder / "listing"
    script.write_text(f'#!/bin/sh\ntouch "{ran}"\necho "{{}}"\n')
    script.chmod(0o755)
    listed = _hosts(tmp_path, folder)
    assert "localhost" in listed["_meta"]["hostvars"] and listed["proxmox"]["hosts"] == ["pve"]
    assert not ran.exists(), "an executable file in the inventory folder was run"
    assert list(_hosts(tmp_path, REPO / "playbooks" / "inventory" / "init.yml")["_meta"]["hostvars"]) == ["localhost"]
    vagrant = tmp_path / "vagrant_ansible_inventory"
    vagrant.write_text(VAGRANT_INVENTORY)
    assert _hosts(tmp_path, vagrant)["claude_vms"]["hosts"] == ["default"]
